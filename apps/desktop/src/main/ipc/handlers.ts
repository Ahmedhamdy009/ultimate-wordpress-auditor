import { app } from 'electron';
import {
  IPC_CHANNELS,
  IPC_ERROR_CODES,
  IPCError,
  AppPingRequestSchema,
  AppPingResponseSchema,
  AppSystemInfoRequestSchema,
  AppSystemInfoResponseSchema,
  AuditValidateTargetRequestSchema,
  AuditValidateTargetResponseSchema,
  validateScanTarget,
  normalizeHost,
  isUrlInScope,
  type AppPingResponse,
  type AppSystemInfoResponse,
  type AuditValidateTargetResponse,
} from '@auditor/shared';
import type { IpcChannelHandler, SecureIpcDispatcher } from './dispatcher.js';

/**
 * Dependency injection contract for deterministic timestamp generation in `app:ping`.
 */
export interface AppPingHandlerDependencies {
  readonly now?: () => number;
}

/**
 * Dependency injection contract for authoritative runtime metadata retrieval in `app:get-system-info`.
 */
export interface SystemInfoRuntimeDependencies {
  readonly getAppVersion?: () => string;
  readonly getVersions?: () => Readonly<Partial<Record<'electron' | 'chrome' | 'node', string>>>;
  readonly getPlatform?: () => string;
  readonly getArch?: () => string;
}

/**
 * Aggregated optional dependencies for core IPC handler registration.
 */
export interface CoreIpcHandlersDependencies {
  readonly ping?: AppPingHandlerDependencies;
  readonly systemInfo?: SystemInfoRuntimeDependencies;
}

const SUPPORTED_PLATFORMS: ReadonlySet<AppSystemInfoResponse['platform']> = new Set([
  'win32',
  'darwin',
  'linux',
]);

function isSupportedPlatform(platform: unknown): platform is AppSystemInfoResponse['platform'] {
  return (
    typeof platform === 'string' &&
    SUPPORTED_PLATFORMS.has(platform as AppSystemInfoResponse['platform'])
  );
}

function isNonEmptyString(value: unknown): value is string {
  return typeof value === 'string' && value.trim().length > 0;
}

/**
 * Creates the `app:ping` Main Process handler.
 *
 * Security & Contract Invariants:
 * - Validates request against `AppPingRequestSchema` (rejects unknown keys and invalid timestamps).
 * - Preserves optional `clientTimestamp` only when supplied and validated.
 * - Generates `serverTimestamp` in the Main Process as a non-negative safe integer.
 * - Validates response against `AppPingResponseSchema` before returning.
 * - Exposes zero internal runtime or system details.
 */
export function createAppPingHandler(
  deps?: AppPingHandlerDependencies,
): IpcChannelHandler<typeof IPC_CHANNELS.APP_PING> {
  const now = deps?.now ?? Date.now;

  return async (request, context): Promise<AppPingResponse> => {
    if (context.signal.aborted) {
      throw new IPCError(
        'Request was aborted before handler execution',
        IPC_ERROR_CODES.INTERNAL_ERROR,
      );
    }

    const parsedRequest = AppPingRequestSchema.safeParse(request);
    if (!parsedRequest.success) {
      throw parsedRequest.error;
    }

    const rawServerTimestamp = now();
    if (typeof rawServerTimestamp !== 'number' || !Number.isFinite(rawServerTimestamp)) {
      throw new IPCError(
        'Invalid server timestamp generated by Main Process',
        IPC_ERROR_CODES.INTERNAL_ERROR,
      );
    }

    const serverTimestamp = Math.trunc(rawServerTimestamp);
    if (!Number.isSafeInteger(serverTimestamp) || serverTimestamp < 0) {
      throw new IPCError(
        'Server timestamp is outside safe integer bounds',
        IPC_ERROR_CODES.INTERNAL_ERROR,
      );
    }

    const clientTimestamp = parsedRequest.data?.timestamp;
    const candidateResponse: AppPingResponse =
      clientTimestamp !== undefined
        ? {
            pong: true,
            clientTimestamp,
            serverTimestamp,
          }
        : {
            pong: true,
            serverTimestamp,
          };

    const parsedResponse = AppPingResponseSchema.safeParse(candidateResponse);
    if (!parsedResponse.success) {
      throw new IPCError(
        'Failed to validate app:ping response against schema',
        IPC_ERROR_CODES.INTERNAL_ERROR,
      );
    }

    return parsedResponse.data;
  };
}

/**
 * Creates the `app:get-system-info` Main Process handler.
 *
 * Security & Contract Invariants:
 * - Validates request against `AppSystemInfoRequestSchema`.
 * - Retrieves `appVersion` from `app.getVersion()` and runtime versions from `process.versions`.
 * - Retrieves `platform` and `arch` from `process.platform` and `process.arch`.
 * - Rejects unsupported platforms (anything other than `'win32' | 'darwin' | 'linux'`) safely
 *   without inventing a fallback platform value.
 * - Returns strictly the six approved fields (`appVersion`, `electronVersion`, `chromeVersion`,
 *   `nodeVersion`, `platform`, `arch`) with no extra fields and no `undefined` values.
 */
export function createGetSystemInfoHandler(
  deps?: SystemInfoRuntimeDependencies,
): IpcChannelHandler<typeof IPC_CHANNELS.APP_GET_SYSTEM_INFO> {
  const getAppVersion = deps?.getAppVersion ?? (() => app.getVersion());
  const getVersions = deps?.getVersions ?? (() => process.versions);
  const getPlatform = deps?.getPlatform ?? (() => process.platform);
  const getArch = deps?.getArch ?? (() => process.arch);

  return async (request, context): Promise<AppSystemInfoResponse> => {
    if (context.signal.aborted) {
      throw new IPCError(
        'Request was aborted before handler execution',
        IPC_ERROR_CODES.INTERNAL_ERROR,
      );
    }

    const parsedRequest = AppSystemInfoRequestSchema.safeParse(request);
    if (!parsedRequest.success) {
      throw parsedRequest.error;
    }

    let rawAppVersion: unknown;
    let rawVersions: Readonly<Partial<Record<'electron' | 'chrome' | 'node', string>>> | undefined;
    let rawPlatform: unknown;
    let rawArch: unknown;

    try {
      rawAppVersion = getAppVersion();
      rawVersions = getVersions();
      rawPlatform = getPlatform();
      rawArch = getArch();
    } catch {
      throw new IPCError(
        'Failed to retrieve runtime system information',
        IPC_ERROR_CODES.INTERNAL_ERROR,
      );
    }

    if (!isSupportedPlatform(rawPlatform)) {
      throw new IPCError('Unsupported operating system platform', IPC_ERROR_CODES.INTERNAL_ERROR);
    }

    const electronVersion = rawVersions?.electron;
    const chromeVersion = rawVersions?.chrome;
    const nodeVersion = rawVersions?.node;

    if (
      !isNonEmptyString(rawAppVersion) ||
      !isNonEmptyString(electronVersion) ||
      !isNonEmptyString(chromeVersion) ||
      !isNonEmptyString(nodeVersion) ||
      !isNonEmptyString(rawArch)
    ) {
      throw new IPCError(
        'Required runtime version or architecture metadata is unavailable',
        IPC_ERROR_CODES.INTERNAL_ERROR,
      );
    }

    const candidateResponse: AppSystemInfoResponse = {
      appVersion: rawAppVersion,
      electronVersion,
      chromeVersion,
      nodeVersion,
      platform: rawPlatform,
      arch: rawArch,
    };

    const parsedResponse = AppSystemInfoResponseSchema.safeParse(candidateResponse);
    if (!parsedResponse.success) {
      throw new IPCError(
        'System information failed response schema validation',
        IPC_ERROR_CODES.INTERNAL_ERROR,
      );
    }

    return parsedResponse.data;
  };
}

/**
 * Creates the `audit:validate-target` Main Process handler.
 *
 * Security & Contract Invariants:
 * - Validates request against `AuditValidateTargetRequestSchema`.
 * - Reuses `@auditor/shared` Scope Guard (`validateScanTarget`, `normalizeHost`, `isUrlInScope`)
 *   exclusively — does NOT implement a second URL parser or duplicate scope logic.
 * - Respects `allowedScope`, `allowAnyPort`, and `allowedPorts` per the shared contract.
 * - Strictly local validation: performs zero network requests, zero crawling, zero Playwright
 *   launches, zero shell execution, and zero remote WordPress access.
 * - Validates response against `AuditValidateTargetResponseSchema` before returning.
 */
export function createValidateTargetHandler(): IpcChannelHandler<
  typeof IPC_CHANNELS.AUDIT_VALIDATE_TARGET
> {
  return async (request, context): Promise<AuditValidateTargetResponse> => {
    if (context.signal.aborted) {
      throw new IPCError(
        'Request was aborted before handler execution',
        IPC_ERROR_CODES.INTERNAL_ERROR,
      );
    }

    const parsedRequest = AuditValidateTargetRequestSchema.safeParse(request);
    if (!parsedRequest.success) {
      throw parsedRequest.error;
    }

    const { targetUrl, allowedScope, options } = parsedRequest.data;
    const normalizedTargetUrl = targetUrl.trim();

    // 1. Validate URL syntax, http/https protocol, and absence of embedded credentials
    // using the authoritative shared Scope Guard.
    const targetValidation = validateScanTarget(normalizedTargetUrl);
    if (!targetValidation.valid) {
      const invalidTargetResponse: AuditValidateTargetResponse = {
        valid: false,
        inScope: false,
        error: targetValidation.reason ?? 'Invalid target URL.',
      };

      const parsedInvalid = AuditValidateTargetResponseSchema.safeParse(invalidTargetResponse);
      if (!parsedInvalid.success) {
        throw new IPCError(
          'Failed to validate target rejection response',
          IPC_ERROR_CODES.INTERNAL_ERROR,
        );
      }
      return parsedInvalid.data;
    }

    // 2. Evaluate URL port-policy validity (`valid`) and scope authorization (`inScope`)
    // independently using the authoritative shared Scope Guard functions:
    // - `inScope` is true iff an explicit `allowedScope` was supplied and `isUrlInScope`
    //   confirms the target matches an allowed host and satisfies its port policy.
    // - `valid` is true iff the target URL passes `validateScanTarget` AND satisfies the
    //   applicable port policy (explicit port on a matching `allowedScope` entry, or
    //   `allowAnyPort` / `allowedPorts` / standard HTTP(80)/HTTPS(443) ports on the target host).
    const hasExplicitAllowedScope = allowedScope !== undefined;

    let inScope: boolean;
    let isPortPermitted: boolean;

    try {
      const targetCanonicalHost = normalizeHost(normalizedTargetUrl);

      if (hasExplicitAllowedScope) {
        inScope = isUrlInScope(normalizedTargetUrl, allowedScope, options);
        if (inScope) {
          isPortPermitted = true;
        } else {
          const hostMatchedScope = isUrlInScope(normalizedTargetUrl, allowedScope, {
            allowAnyPort: true,
          });
          isPortPermitted = hostMatchedScope
            ? false
            : isUrlInScope(normalizedTargetUrl, [targetCanonicalHost], options);
        }
      } else {
        inScope = false;
        isPortPermitted = isUrlInScope(normalizedTargetUrl, [targetCanonicalHost], options);
      }
    } catch {
      inScope = false;
      isPortPermitted = false;
    }

    const candidateResponse: AuditValidateTargetResponse = isPortPermitted
      ? {
          valid: true,
          normalizedUrl: normalizedTargetUrl,
          inScope,
        }
      : {
          valid: false,
          inScope: false,
          error: 'Target URL is outside the permitted scope or port policy.',
        };

    const parsedResponse = AuditValidateTargetResponseSchema.safeParse(candidateResponse);
    if (!parsedResponse.success) {
      throw new IPCError(
        'Failed to validate audit:validate-target response against schema',
        IPC_ERROR_CODES.INTERNAL_ERROR,
      );
    }

    return parsedResponse.data;
  };
}

/**
 * Registers the three approved Phase 1.2.3.4 Main Process handlers onto the provided
 * `SecureIpcDispatcher`.
 *
 * Never invokes `ipcMain.handle` directly; all registrations pass through `SecureIpcDispatcher`
 * and `CentralIpcRegistrationManager`.
 */
export function registerCoreIpcHandlers(
  dispatcher: SecureIpcDispatcher,
  deps?: CoreIpcHandlersDependencies,
): void {
  dispatcher.registerHandler(IPC_CHANNELS.APP_PING, createAppPingHandler(deps?.ping));
  dispatcher.registerHandler(
    IPC_CHANNELS.APP_GET_SYSTEM_INFO,
    createGetSystemInfoHandler(deps?.systemInfo),
  );
  dispatcher.registerHandler(IPC_CHANNELS.AUDIT_VALIDATE_TARGET, createValidateTargetHandler());
}
